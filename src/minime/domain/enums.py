"""Domain enumeration types for mini me."""

from enum import Enum


class ProjectStatus(str, Enum):
    ACTIVE = "ACTIVE"
    DISABLED = "DISABLED"
    ARCHIVED = "ARCHIVED"


class ChangeStatus(str, Enum):
    DISCOVERED = "DISCOVERED"
    READY = "READY"
    IN_PROGRESS = "IN_PROGRESS"
    BLOCKED = "BLOCKED"
    DONE = "DONE"
    CANCELLED = "CANCELLED"


class ReadinessState(str, Enum):
    READY = "READY"
    NOT_READY = "NOT_READY"
    BLOCKED = "BLOCKED"


class AgentRole(str, Enum):
    IMPLEMENTER = "implementer"
    REVIEWER = "reviewer"
    AUDITOR = "auditor"
    HELPER = "helper"


class JobStatus(str, Enum):
    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    CHECKS_RUNNING = "CHECKS_RUNNING"
    CHECKS_PASSED = "CHECKS_PASSED"
    CHECKS_FAILED = "CHECKS_FAILED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class EventType(str, Enum):
    PROJECT_REGISTERED = "PROJECT_REGISTERED"
    PROJECT_UPDATED = "PROJECT_UPDATED"
    CHANGE_DISCOVERED = "CHANGE_DISCOVERED"
    READINESS_EVALUATED = "READINESS_EVALUATED"
    WORK_BOUND = "WORK_BOUND"
    SYNC_FAILED = "SYNC_FAILED"
    SYNC_RECONCILED = "SYNC_RECONCILED"
    STATUS_CHECKED = "STATUS_CHECKED"
    JOB_QUEUED = "JOB_QUEUED"
    JOB_RUNNING = "JOB_RUNNING"
    JOB_CHECKS_RUNNING = "JOB_CHECKS_RUNNING"
    JOB_CHECKS_PASSED = "JOB_CHECKS_PASSED"
    JOB_CHECKS_FAILED = "JOB_CHECKS_FAILED"
    JOB_FAILED = "JOB_FAILED"
    JOB_CANCELLED = "JOB_CANCELLED"
    JOB_TIMEOUT = "JOB_TIMEOUT"
    INCOMPLETE_TASKS = "INCOMPLETE_TASKS"
